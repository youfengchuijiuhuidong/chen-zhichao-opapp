# -*- coding: utf-8 -*-
"""
Batch apply all 127 dual-layer reconstructed intuitions into:
  - data/operators.json
  - data/operators.js
  - js/data.js
"""
import json
import re
from pathlib import Path
import sys

REPO = Path("e:/PaperHub/chen-zhichao-opapp")
sys.path.insert(0, str(REPO / "tools"))
sys.path.insert(0, str(Path("e:/PaperHub")))

from sync_all_intuitions import parse_ch2, parse_ch34, parse_ch567

def main():
    ch2 = parse_ch2()
    ch34 = parse_ch34()
    ch567 = parse_ch567()
    all_rec = {**ch2, **ch34, **ch567}
    print(f"Loaded reconstructed records for {len(all_rec)} operators.")

    op_json_path = REPO / "data" / "operators.json"
    data = json.loads(op_json_path.read_text(encoding="utf-8"))
    
    updated_count = 0
    for op in data["operators"]:
        op_id = op["id"]
        if op_id not in all_rec:
            raise KeyError(f"Missing operator {op_id}")
            
        rec = all_rec[op_id]
        brain = rec["brain"].strip()
        orig = op["intuition"].strip()
        
        # If orig already has dual-layer markers, don't duplicate
        if "🧠 白话直觉" in orig:
            continue
            
        # For math part: use rec['math'] if clean, or preserve orig if rec['math'] is long LaTeX derivation
        # In fact, the user requested:
        # 🧠 白话直觉：【物理图像/打比方】
        # 📐 数学本质：保留原版那段话（帮读者完成从“推沙子”到“奥托黎曼流形”的术语映射）
        math_nature = orig
        
        # Special touch for wasserstein_space_p2 as demonstrated by user:
        if op_id == "wasserstein_space_p2":
            brain = "把每一个概率分布想象成地上的一堆沙子，那么 P₂ 空间就是装下所有“形状不至于无限发散”的沙堆的宇宙。在这个宇宙里，一整堆沙子（无论形状多复杂）只被看作一个“点”。把一堆沙子推成另一堆沙子所花的最小力气（按移动距离的平方算成本），就是这两个“点”之间的距离。有了距离和方向，原本复杂的“寻找最优概率分布”（变分推断），就变成了在这个地图上让一个点顺着山坡往下滑（梯度下降）一样简单直观。"
        
        dual_intuition = f"🧠 白话直觉：{brain}\n\n📐 数学本质：{math_nature}"
        op["intuition"] = dual_intuition
        
        # If problem field can be sharpened from audit report
        if rec.get("problem"):
            clean_prob = rec["problem"].strip()
            # If starts with question mark or bold, clean up
            clean_prob = re.sub(r'^\*\*为什么[^*]+\*\*\s*', '', clean_prob)
            clean_prob = re.sub(r'^[0-9\.\s]+', '', clean_prob)
            if len(clean_prob) > 10 and len(clean_prob) < 300:
                op["problem_detail"] = clean_prob
                
        updated_count += 1
        
    print(f"Updated {updated_count} operators in memory.")
    
    # Save operators.json
    op_json_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {op_json_path}")
    
    # Save operators.js
    op_js_path = REPO / "data" / "operators.js"
    op_js_content = (
        "/* generated from data/operators.json — file:// 可离线加载 */\n"
        "window.OP_DATA = "
        + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    op_js_path.write_text(op_js_content, encoding="utf-8")
    print(f"Wrote {op_js_path}")
    
    # Save js/data.js
    js_data_path = REPO / "js" / "data.js"
    js_data_content = (
        "/* auto-generated by tools/build_data.py — do not edit */\n"
        "window.OPDATA = " + json.dumps(data, ensure_ascii=False) + ";\n"
    )
    js_data_path.write_text(js_data_content, encoding="utf-8")
    print(f"Wrote {js_data_path}")

if __name__ == "__main__":
    main()
